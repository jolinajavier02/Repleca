export type ProjectTemplate = {
  id: string;
  mode: string;
  name: string;
  category: string;
  formatId: string;
  description: string;
  style: TemplateStyle;
  variant: number;
  title: string;
  subtitle: string;
  color?: string;
  body?: string;
  cells?: string[][];
  css?: string;
  note?: string;
  scenes?: {
    name: string;
    title: string;
    subtitle: string;
    variant: number;
    duration: number;
  }[];
};
const t = (
  id: string,
  mode: string,
  name: string,
  category: string,
  formatId: string,
  style: TemplateStyle,
  variant: number,
  title: string,
  subtitle: string,
  description: string,
): ProjectTemplate => ({
  id,
  mode,
  name,
  category,
  formatId,
  style,
  variant,
  title,
  subtitle,
  description,
});
const video = (
  id: string,
  name: string,
  platform: string,
  formatId: string,
  title: string,
  description: string,
  variant: number,
) => ({
  ...t(
    id,
    "video",
    name,
    platform,
    formatId,
    "video",
    variant,
    title,
    "MAKE IT YOURS",
    description,
  ),
  scenes: [
    {
      name: "The hook",
      title,
      subtitle: "START WITH SOMETHING WORTH WATCHING",
      variant,
      duration: 3,
    },
    {
      name: "The story",
      title: "Show how it happens.",
      subtitle: "ADD YOUR FOOTAGE AND YOUR PERSPECTIVE",
      variant: (variant + 1) % 6,
      duration: 8,
    },
    {
      name: "The finish",
      title: "Try it for yourself.",
      subtitle: "YOUR NEXT STEP GOES HERE",
      variant: (variant + 2) % 6,
      duration: 4,
    },
  ],
});
const deck = (
  id: string,
  name: string,
  category: string,
  formatId: string,
  titles: string[],
  subtitles: string[],
  variant: number,
) => ({
  ...t(
    id,
    "present",
    name,
    category,
    formatId,
    "presentation",
    variant,
    titles[0],
    subtitles[0],
    "A coordinated, editable slide deck with a clear story and matching layouts.",
  ),
  scenes: titles.map((title, i) => ({
    name:
      ["Opening", "The idea", "The plan", "Next steps"][i] || `Slide ${i + 1}`,
    title,
    subtitle: subtitles[i] || "",
    variant: (variant + i) % 6,
    duration: 8,
  })),
});
